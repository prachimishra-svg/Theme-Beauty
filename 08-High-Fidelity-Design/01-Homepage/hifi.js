/* NUDGE high-fidelity Homepage: photo slots and scroll reveal.
   Every media area of the wireframe is a component ".img". images/manifest.js (generated by build-hifi.ps1) says which photograph belongs in which slot (section + order) and which photographs exist in images/.
   A slot with a photograph gets an <img> (cover crop, lazy); a slot without one keeps its tonal brand surface with the wireframe caption hidden. Add ?review=1 to the address to show each empty slot's file name. */
(function () {
  'use strict';
  var M = window.NUDGE_HIFI || { sections: {}, files: {}, alt: {} }, root = document.documentElement, review = /[?&]review=1/.test(location.search);
  if (review) root.classList.add('hifi-review');
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  function fill() {
    var names = Object.keys(M.sections);
    [].forEach.call(document.querySelectorAll('[data-section]'), function (sec) {
      if (sec.closest('.rv')) return; var nm = sec.getAttribute('data-section'), hit = names.filter(function (n) { return nm.indexOf(n) === 0; })[0]; if (!hit) return;
      var keys = M.sections[hit], slots = [].filter.call(sec.querySelectorAll('.img'), function (e) { return !e.parentElement.closest('.img'); });
      slots.forEach(function (el, i) {
        var key = keys[i]; if (!key) return; el.setAttribute('data-slot', key); var file = M.files[key];
        if (!file) { el.classList.add('no-photo'); if (review) el.setAttribute('data-slot-label', key); return; }
        var im = new Image(); im.className = 'hifi-img'; im.alt = M.alt[key] || ''; im.decoding = 'async'; im.loading = i === 0 && hit === 'Hero Banner' ? 'eager' : 'lazy';
        im.onload = function () { el.classList.add('has-photo'); }; im.onerror = function () { im.remove(); el.classList.add('no-photo'); };
        im.src = (M.base || 'images/') + file; el.appendChild(im);
      });
    });
  }
  /* mega menu cards: the two photo cards of each top-level menu (their wireframe slots are plain .ph tiles) */
  function fillMenus() {
    [].forEach.call(document.querySelectorAll('[data-mega]'), function (m) {
      var keys = (M.menus || {})[m.getAttribute('data-mega')]; if (!keys) return;
      var tiles = [].slice.call(m.querySelectorAll('[data-mega-panel] .ph, [data-mega-panel] .ph-b'));
      tiles.forEach(function (el, i) { var key = keys[i]; if (!key) return; el.setAttribute('data-slot', key); var file = M.files[key]; if (!file) { el.classList.add('no-photo'); return; } var im = new Image(); im.className = 'hifi-img'; im.alt = M.alt[key] || ''; im.decoding = 'async'; im.loading = 'lazy'; im.onload = function () { el.classList.add('has-photo'); }; im.onerror = function () { im.remove(); el.classList.add('no-photo'); }; im.src = (M.base || 'images/') + file; el.appendChild(im); });
    });
  }
  /* gentle reveal for the sections below the first fold; a timer reveals everything even if the observer never fires */
  function reveal() {
    if (reduce || !('IntersectionObserver' in window)) return;
    var secs = [].filter.call(document.querySelectorAll('main > section[data-section]'), function (s) { return !/^(Announcement|Header|Hero)/.test(s.getAttribute('data-section')) && s.getBoundingClientRect().top > window.innerHeight * 0.9; });
    secs.forEach(function (s) { s.classList.add('hifi-reveal'); });
    var io = new IntersectionObserver(function (es) { es.forEach(function (e) { if (e.isIntersecting) { e.target.classList.add('is-in'); io.unobserve(e.target); } }); }, { rootMargin: '0px 0px -8% 0px', threshold: 0.05 });
    secs.forEach(function (s) { io.observe(s); });
    setTimeout(function () { secs.forEach(function (s) { s.classList.add('is-in'); }); }, 4000);
  }
  /* the market menu is built by currency.js at run time and carries a wireframe note */
  function marketNote() {
    var m = document.getElementById('market-menu'); if (!m) return;
    function fix() { var w = document.createTreeWalker(m, NodeFilter.SHOW_TEXT, null), n; while ((n = w.nextNode())) { if (/Sample exchange rates/.test(n.nodeValue)) n.nodeValue = 'Prices are shown at indicative exchange rates.'; } }
    fix(); new MutationObserver(fix).observe(m, { childList: true, subtree: true });
  }
  function init() { fill(); fillMenus(); marketNote(); reveal(); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})();