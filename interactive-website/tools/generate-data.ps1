# Generates interactive-website/data/*.js from the wireframes themselves (nothing is invented here):
#   products.js     the 25 PLP sample products, copied verbatim from the PLP data array (03-Wireframes/00-Shared-Tailwind-Foundation/src/plp.src.html or its saved copy)
#   collections.js  every collection link of the mega menus and footer (from documentation/data/link-inventory.json)
# Usage: .\tools\generate-data.ps1
$ErrorActionPreference = 'Stop'
$IW = Split-Path -Parent $PSScriptRoot; $PRJ = Split-Path -Parent $IW; $utf8 = New-Object Text.UTF8Encoding($false)
$plp = Join-Path $PRJ '03-Wireframes\00-Shared-Tailwind-Foundation\src\plp.src.html'; $t = [IO.File]::ReadAllText($plp, $utf8)
$all = [regex]::Match($t, 'var ALL=\[[^\]]*\]').Value; $fam = [regex]::Match($t, 'FAM=\[\[.*?\]\]\]').Value
$m = [regex]::Match($t, 'var P=\[\r?\n([\s\S]*?)\r?\n\s*\];'); if (-not $m.Success -or -not $all) { throw 'PLP data array not found' }
$rows = $m.Groups[1].Value.Trim()
$js = @"
/* GENERATED by tools/generate-data.ps1 from the PLP wireframe's own sample data. Do not edit by hand.
   Tuple order: name, type, ml, price, compare-at, concerns, skin types, attribute line, badge, rating, reviews, shade indexes, low stock, sold out, unit price shown, ingredients. */
(function (g) {
  var NS = g.NudgeSite = g.NudgeSite || {}; NS.data = NS.data || {};
  $all;
  var RAW = [
$rows
  ];
  var FAMILIES = [["Rose","#D99BAA"],["Berry","#8E3F5A"],["Peach","#EDB9A9"],["Mauve","#B48A9A"],["Coral","#E8907E"]];
  NS.data.plpRaw = RAW; NS.data.shadeFamilies = FAMILIES;
})(window);
"@
New-Item -ItemType Directory -Force (Join-Path $IW 'data') | Out-Null
[IO.File]::WriteAllText((Join-Path $IW 'data\plp-raw.js'), $js, $utf8)
# collections from the real links
$inv = [IO.File]::ReadAllText((Join-Path $IW 'documentation\data\link-inventory.json'), $utf8) | ConvertFrom-Json
$homeRec = @($inv | Where-Object { $_.number -eq 1 })[0]
$cols = @($homeRec.data.items | Where-Object { $_.tag -eq 'a' -and $_.href -like '#collection-*' } | Group-Object href | ForEach-Object { $x = $_.Group[0]; [pscustomobject]@{ handle = $_.Name.Substring(12); title = (($x.text -replace 'IMAGE PLACEHOLDER4:5', '' -replace 'Shop now$', '').Trim()) } } | Sort-Object handle)
$lines = $cols | ForEach-Object { '    ["' + $_.handle + '", "' + ($_.title -replace '"', '\"') + '"]' }
$cjs = "/* GENERATED by tools/generate-data.ps1 from the collection links in the header mega menus and footer. Do not edit by hand. [handle, title] */`n(function (g) {`n  var NS = g.NudgeSite = g.NudgeSite || {}; NS.data = NS.data || {};`n  NS.data.collectionLinks = [`n" + ($lines -join ",`n") + "`n  ];`n})(window);`n"
[IO.File]::WriteAllText((Join-Path $IW 'data\collection-links.js'), $cjs, $utf8)
"plp products: $(([regex]::Matches($rows, '^\s*\[', 'Multiline')).Count); collection links: $($cols.Count)"
