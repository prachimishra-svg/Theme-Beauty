# Regenerates the GENERATED theme files from the single sources, so nothing is copied by hand and nothing is duplicated as a second source of truth:
#   assets/variables.css        <- 02-Design-Variables/Styles/variables.css (the Design Variables)
#   assets/*.woff2              <- 05-Assets/Fonts
#   snippets/fonts.liquid       <- the @font-face rules of 01-Design-System/Styles/foundation.css, with Liquid asset_url paths
#   snippets/icon-sprite.liquid <- 03-Wireframes/00-Shared-Tailwind-Foundation/partials/sprite.html (same icons as 05-Assets/Icons)
#   assets/theme.css            <- the CSS the Tailwind Play script generates for the wireframe Homepage (plus any theme-only markup passed with -ExtraHtml),
#                                  plus the foundation.css compatibility aliases. INTERIM: replace with a Tailwind CLI build when Node or the standalone binary is available.
# Hand-written files that this script never touches: assets/theme-shopify.css, assets/nav.js, assets/drawer.js, assets/homepage.js, assets/localization.js, assets/cart.js.
# Usage: .\tools\build-theme.ps1 [-ExtraHtml path-to-rendered-theme.html] [-SkipCss]
param([string]$ExtraHtml = '', [switch]$SkipCss)
$ErrorActionPreference = 'Stop'
$T = Split-Path -Parent $PSScriptRoot; $P = Split-Path -Parent $T
$utf8 = New-Object Text.UTF8Encoding($false)
$hdr = '/* GENERATED by 06-Shopify-Theme/tools/build-theme.ps1 from {0}. Do not edit here; change the source and run the script again. */'
New-Item -ItemType Directory -Force "$T\assets", "$T\snippets" | Out-Null

# 1. Design Variables
$v = [IO.File]::ReadAllText("$P\02-Design-Variables\Styles\variables.css", $utf8)
[IO.File]::WriteAllText("$T\assets\variables.css", ($hdr -f '02-Design-Variables/Styles/variables.css') + "`n" + $v, $utf8)

# 2. Fonts (+ Liquid font-face snippet)
Get-ChildItem "$P\05-Assets\Fonts" -Filter *.woff2 | ForEach-Object { Copy-Item $_.FullName "$T\assets\$($_.Name)" -Force }
$fc = [IO.File]::ReadAllText("$P\01-Design-System\Styles\foundation.css", $utf8)
$faces = [regex]::Matches($fc, '@font-face\s*\{[^}]*\}') | ForEach-Object { $_.Value }
if ($faces.Count -lt 3) { throw "expected 3 @font-face rules in foundation.css, found $($faces.Count)" }
$faces = $faces | ForEach-Object { [regex]::Replace($_, 'url\("\.\./\.\./05-Assets/Fonts/([^"]+)"\)', { param($m) "url('{{ '" + $m.Groups[1].Value + "' | asset_url }}')" }) }
$pre = [regex]::Matches($fc, 'Fonts/([a-z0-9-]+\.woff2)') | ForEach-Object { $_.Groups[1].Value } | Select-Object -Unique | Where-Object { $_ -in 'cormorant-var.woff2', 'dm-sans-var.woff2' }
$fonts = "{%- comment -%} GENERATED by tools/build-theme.ps1 from 01-Design-System/Styles/foundation.css. Do not edit. {%- endcomment -%}`n"
$pre | ForEach-Object { $fonts += "<link rel=`"preload`" href=`"{{ '$_' | asset_url }}`" as=`"font`" type=`"font/woff2`" crossorigin>`n" }
$fonts += "<style data-shopify>`n" + ($faces -join "`n") + "`n</style>`n"
[IO.File]::WriteAllText("$T\snippets\fonts.liquid", $fonts, $utf8)

# 2b. Drawer behaviour (native <dialog>: focus trap, scroll lock, focus return) is the Design System's own script
$dj = [IO.File]::ReadAllText("$P\01-Design-System\Scripts\drawer.js", $utf8)
[IO.File]::WriteAllText("$T\assets\drawer.js", ($hdr -f '01-Design-System/Scripts/drawer.js') + "`n" + $dj, $utf8)
# 3. Icon sprite
$sprite = [IO.File]::ReadAllText("$P\03-Wireframes\00-Shared-Tailwind-Foundation\partials\sprite.html", $utf8)
[IO.File]::WriteAllText("$T\snippets\icon-sprite.liquid", "{%- comment -%} GENERATED by tools/build-theme.ps1 from 03-Wireframes/00-Shared-Tailwind-Foundation/partials/sprite.html. Do not edit. {%- endcomment -%}`n" + $sprite, $utf8)

# 4. Compiled CSS (interim): let Chrome run the Tailwind Play script on the Homepage wireframe and read back the CSS it generated
if (-not $SkipCss) {
  $wfHome = Get-ChildItem "$P\03-Wireframes" -Recurse -Filter Homepage.html | Where-Object { $_.FullName -match '\\\d\d-NUDGE' } | Select-Object -First 1
  if (-not $wfHome) { throw 'wireframe Homepage.html not found (run 03-Wireframes/00-Shared-Tailwind-Foundation/build.ps1 -All first)' }
  $html = [IO.File]::ReadAllText($wfHome.FullName, $utf8)
  $jsCls = [IO.File]::ReadAllText("$PSScriptRoot\js-classes.html", $utf8)
  $html = $html.Replace('</body>', '<div hidden id="js-classes">' + $jsCls + '</div></body>')
  if ($ExtraHtml) {
    $x = [IO.File]::ReadAllText($ExtraHtml, $utf8); $bm = [regex]::Match($x, '<body[^>]*>([\s\S]*)</body>'); $frag = if ($bm.Success) { $bm.Groups[1].Value } else { $x }
    $frag = [regex]::Replace($frag, '<script[\s\S]*?</script>', '')
    $html = $html.Replace('</body>', '<div hidden id="theme-extra">' + $frag + '</div></body>')
  }
  $tmpPage = Join-Path $wfHome.DirectoryName '_theme-css-extract.tmp.html'
  try {
    [IO.File]::WriteAllText($tmpPage, $html, $utf8)
    $dump = Join-Path ([IO.Path]::GetTempPath()) 'nudge-css-dump.html'
    $u = 'file:///' + (($tmpPage -replace '\\', '/') -replace ' ', '%20') + '?embed=1&ann=0'
    Start-Process -FilePath 'C:\Program Files\Google\Chrome\Application\chrome.exe' -ArgumentList @('--headless=new', '--disable-gpu', '--allow-file-access-from-files', '--window-size=1440,900', '--virtual-time-budget=15000', '--dump-dom', "`"$u`"") -RedirectStandardOutput $dump -RedirectStandardError "$dump.err" -Wait -NoNewWindow
    $dom = [IO.File]::ReadAllText($dump, $utf8)
  } finally { if (Test-Path $tmpPage) { Remove-Item $tmpPage -Force } }
  $css = $null
  foreach ($m in [regex]::Matches($dom, '<style>([\s\S]*?)</style>')) { if ($m.Groups[1].Value.TrimStart().StartsWith('*, ::before')) { $css = $m.Groups[1].Value } }
  if (-not $css) { throw 'could not find the Tailwind Play output in the rendered page' }
  $alias = [regex]::Match($fc, ':root\s*\{\s*--gutter:[\s\S]*?\}').Value
  $out = ($hdr -f 'the Tailwind Play script output for the wireframe Homepage (interim; see tools/build-theme.ps1)') + "`n/* foundation.css compatibility aliases */`n" + $alias + "`n" + $css.Trim() + "`n"
  [IO.File]::WriteAllText("$T\assets\theme.css", $out, $utf8)
  "theme.css: {0} KB" -f [Math]::Round($out.Length / 1KB, 1)
}
"built: assets/variables.css, fonts x$(@(Get-ChildItem "$T\assets" -Filter *.woff2).Count), snippets/fonts.liquid, snippets/icon-sprite.liquid"
