# Static checks for the theme (our own linter: Shopify's Theme Check is not available here). Errors fail the run; warnings are advice.
# Usage: .\tools\lint-theme.ps1 [-Quiet]      Returns @{ Errors; Warnings } and prints them.
# Checks: JSON validity (templates, groups, config, locales) | Liquid tag balance | every render/section/sections target exists | every asset_url file exists |
#         every translation key exists | {{ }} balance | wireframe leftovers (@@, data-c, .ann) | hard-coded hex colours | section schema rules (name length, unique ids,
#         valid types, select/range/radio defaults and options, presets or enabled_on, block types used in markup exist, max_blocks <= 50, block.shopify_attributes on repeated blocks) |
#         JSON templates and groups only use known sections, block types and setting ids.
param([switch]$Quiet)
$T = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object Text.UTF8Encoding($false)
$errors = New-Object System.Collections.Generic.List[string]; $warns = New-Object System.Collections.Generic.List[string]
function Err($f, $m) { $errors.Add("$f : $m") }
function Warn($f, $m) { $warns.Add("$f : $m") }
$validTypes = 'checkbox', 'number', 'radio', 'range', 'select', 'text', 'textarea', 'article', 'blog', 'collection', 'collection_list', 'color', 'color_background', 'color_scheme', 'color_scheme_group', 'font_picker', 'html', 'image_picker', 'inline_richtext', 'link_list', 'liquid', 'metaobject', 'metaobject_list', 'page', 'product', 'product_list', 'richtext', 'text_alignment', 'url', 'video', 'video_url', 'header', 'paragraph', 'style_panel'
$noLabel = 'header', 'paragraph'
function Rel($p) { $p.Substring($T.Length + 1) -replace '\\', '/' }

# ---------- inventory ----------
$liq = @(); foreach ($d in 'layout', 'sections', 'snippets', 'templates') { if (Test-Path "$T\$d") { $liq += Get-ChildItem "$T\$d" -Recurse -File -Filter *.liquid } }
$json = @(); foreach ($d in 'sections', 'templates', 'config', 'locales') { if (Test-Path "$T\$d") { $json += Get-ChildItem "$T\$d" -Recurse -File -Filter *.json } }
$snippets = @{}; Get-ChildItem "$T\snippets" -File -Filter *.liquid -ErrorAction SilentlyContinue | ForEach-Object { $snippets[$_.BaseName] = 1 }
$sectionFiles = @{}; Get-ChildItem "$T\sections" -File -Filter *.liquid -ErrorAction SilentlyContinue | ForEach-Object { $sectionFiles[$_.BaseName] = 1 }
$assets = @{}; Get-ChildItem "$T\assets" -File -ErrorAction SilentlyContinue | ForEach-Object { $assets[$_.Name] = 1 }
$localeKeys = @{}
$parsed = @{}
foreach ($f in $json) {
  $rel = Rel $f.FullName
  try { $parsed[$rel] = ([IO.File]::ReadAllText($f.FullName, $utf8) | ConvertFrom-Json) } catch { Err $rel "invalid JSON: $($_.Exception.Message)" }
}
function Flat($o, $prefix) { if ($o -is [pscustomobject] -and $o.PSObject.Properties.Name -contains 'other') { $script:localeKeys[$prefix] = 1 } elseif ($o -is [pscustomobject]) { foreach ($p in $o.PSObject.Properties) { Flat $p.Value ($(if ($prefix) { "$prefix.$($p.Name)" } else { $p.Name })) } } else { $script:localeKeys[$prefix] = 1 } }
if ($parsed.ContainsKey('locales/en.default.json')) { Flat $parsed['locales/en.default.json'] '' } else { Err 'locales/en.default.json' 'missing' }

# ---------- per Liquid file ----------
$blockTags = 'if', 'unless', 'case', 'for', 'capture', 'form', 'paginate', 'tablerow', 'style', 'stylesheet', 'javascript', 'schema'
$staticSections = @{}; foreach ($lf in (Get-ChildItem "$T\layout" -Filter *.liquid)) { foreach ($sm in [regex]::Matches([IO.File]::ReadAllText($lf.FullName, $utf8), '\{%-?\s*section\s+[''"]([^''"]+)[''"]')) { $staticSections[$sm.Groups[1].Value] = 1 } }
$sectionSchemas = @{}
foreach ($f in $liq) {
  $rel = Rel $f.FullName; $src = [IO.File]::ReadAllText($f.FullName, $utf8)
  $generated = $src -match 'GENERATED by'
  # schema
  $schemaText = $null; $sm = [regex]::Match($src, '\{%-?\s*schema\s*-?%\}([\s\S]*?)\{%-?\s*endschema\s*-?%\}')
  if ($sm.Success) { $schemaText = $sm.Groups[1].Value }
  $code = $src
  $code = [regex]::Replace($code, '\{%-?\s*schema\s*-?%\}[\s\S]*?\{%-?\s*endschema\s*-?%\}', '')
  $code = [regex]::Replace($code, '\{%-?\s*raw\s*-?%\}[\s\S]*?\{%-?\s*endraw\s*-?%\}', '')
  $code = [regex]::Replace($code, '\{%-?\s*comment\s*-?%\}[\s\S]*?\{%-?\s*endcomment\s*-?%\}', '')
  # {% liquid %} blocks: check their inner balance on their own, then drop them
  foreach ($lm in [regex]::Matches($code, '\{%-?\s*liquid\b([\s\S]*?)-?%\}')) {
    $st = New-Object System.Collections.Stack
    foreach ($ln in ($lm.Groups[1].Value -split "`n")) { $w = ($ln.Trim() -split '\s+')[0]; if ($blockTags -contains $w) { $st.Push($w) } elseif ($w -like 'end*' -and $blockTags -contains $w.Substring(3)) { if ($st.Count -eq 0 -or $st.Pop() -ne $w.Substring(3)) { Err $rel "unbalanced {% liquid %}: $w" } } }
    if ($st.Count) { Err $rel "unclosed in {% liquid %}: $($st.ToArray() -join ',')" }
  }
  $code = [regex]::Replace($code, '\{%-?\s*liquid\b[\s\S]*?-?%\}', '')
  # tag balance
  $stack = New-Object System.Collections.Stack
  foreach ($m in [regex]::Matches($code, '\{%-?\s*(\w+)')) {
    $tag = $m.Groups[1].Value
    if ($blockTags -contains $tag) { $stack.Push($tag) }
    elseif ($tag -like 'end*' -and $blockTags -contains $tag.Substring(3)) { if ($stack.Count -eq 0) { Err $rel "extra {% $tag %}" } elseif ($stack.Peek() -ne $tag.Substring(3)) { Err $rel "{% $tag %} closes {% $($stack.Peek()) %}"; [void]$stack.Pop() } else { [void]$stack.Pop() } }
  }
  if ($stack.Count) { Err $rel "unclosed tags: $($stack.ToArray() -join ', ')" }
  if (([regex]::Matches($code, '\{\{')).Count -ne ([regex]::Matches($code, '\}\}')).Count) { Err $rel 'unbalanced {{ }}' }
  # references
  foreach ($m in [regex]::Matches($code, '\{%-?\s*render\s+[''"]([^''"]+)[''"]')) { if (-not $snippets.ContainsKey($m.Groups[1].Value)) { Err $rel "render target missing: snippets/$($m.Groups[1].Value).liquid" } }
  foreach ($m in [regex]::Matches($code, '\{%-?\s*section\s+[''"]([^''"]+)[''"]')) { if (-not $sectionFiles.ContainsKey($m.Groups[1].Value)) { Err $rel "section target missing: sections/$($m.Groups[1].Value).liquid" } }
  foreach ($m in [regex]::Matches($code, '\{%-?\s*sections\s+[''"]([^''"]+)[''"]')) { if (-not (Test-Path "$T\sections\$($m.Groups[1].Value).json")) { Err $rel "section group missing: sections/$($m.Groups[1].Value).json" } }
  foreach ($m in [regex]::Matches($code, '[''"]([^''"]+)[''"]\s*\|\s*asset_url')) { if (-not $assets.ContainsKey($m.Groups[1].Value)) { Err $rel "asset missing: assets/$($m.Groups[1].Value)" } }
  foreach ($m in [regex]::Matches($code, '[''"]([a-z0-9_]+(?:\.[a-z0-9_]+)+)[''"]\s*\|\s*t\b')) { if (-not $localeKeys.ContainsKey($m.Groups[1].Value)) { Err $rel "translation key missing in locales/en.default.json: $($m.Groups[1].Value)" } }
  # Shopify does not allow filters inside render/include parameters (assign the value first)
  foreach ($rm in [regex]::Matches($code, '\{%-?\s*render\s+[^%]*?-?%\}')) {
    $inner = [regex]::Replace($rm.Value, "'[^']*'|""[^""]*""", '""')
    if ($inner -match '\|') { Err $rel ('filter used inside a render parameter (Shopify rejects this; assign the value first): ' + $rm.Value.Substring(0, [Math]::Min(100, $rm.Value.Length))) }
  }  # leftovers from the wireframe build
  if (-not $generated) {
    if ($src -match '@@') { Err $rel 'wireframe placeholder "@@" left in file' }
    if ($src -match 'data-c="') { Err $rel 'wireframe data-c edit hook left in file' }
    if ($src -match 'class="ann"|class="ann ') { Err $rel 'review annotation (.ann) left in file' }
    if ($src -match '(?<![\w&])#[0-9a-fA-F]{6}\b|(?<![\w&])#[0-9a-fA-F]{3}\b(?![\w-])' -and $src -notmatch 'href="#') { Warn $rel 'possible hard-coded hex colour' }
    $stripped = [regex]::Replace($src, 'href="#[^"]*"|id="[^"]*"|url\([^)]*\)', '')
    if ($rel -like 'sections/*' -or $rel -like 'snippets/*') { foreach ($hm in [regex]::Matches($stripped, '(?<![\w&{-])#[0-9a-fA-F]{6}\b')) { Warn $rel "hard-coded colour $($hm.Value)" } }
  }
  # section schema
  if ($rel -like 'sections/*.liquid') {
    $name = [IO.Path]::GetFileNameWithoutExtension($rel)
    if (-not $schemaText) { Err $rel 'section has no {% schema %}'; continue }
    try { $sc = $schemaText | ConvertFrom-Json } catch { Err $rel "schema is not valid JSON: $($_.Exception.Message)"; continue }
    $sectionSchemas[$name] = $sc
    if (-not $sc.name) { Err $rel 'schema.name missing' } elseif ($sc.name.Length -gt 25) { Warn $rel "schema.name is $($sc.name.Length) characters (Shopify shows up to 25 cleanly)" }
    $ids = @{}
    $chk = { param($settings, $ctx)
      foreach ($s in @($settings)) {
        if (-not $s) { continue }
        if ($validTypes -notcontains $s.type) { Err $rel "$ctx : unknown setting type '$($s.type)'" ; continue }
        if ($noLabel -notcontains $s.type) {
          if (-not $s.id) { Err $rel "$ctx : setting without id ($($s.type))" } else { if ($script:ids.ContainsKey("$ctx|$($s.id)")) { Err $rel "$ctx : duplicate setting id '$($s.id)'" }; $script:ids["$ctx|$($s.id)"] = 1 }
          if (-not $s.label) { Err $rel "$ctx : setting '$($s.id)' has no label" }
        }
        if ($s.type -eq 'select' -or $s.type -eq 'radio') {
          if (-not $s.options -or @($s.options).Count -lt 2) { Err $rel "$ctx : '$($s.id)' needs at least two options" }
          else { foreach ($o in @($s.options)) { if ($null -eq $o.value -or -not $o.label) { Err $rel "$ctx : '$($s.id)' option without value/label" } }
            if ($null -ne $s.default -and (@($s.options | ForEach-Object { $_.value }) -notcontains $s.default)) { Err $rel "$ctx : '$($s.id)' default '$($s.default)' is not one of its options" }
            if ($null -eq $s.default) { Warn $rel "$ctx : '$($s.id)' has no default (first option is used)" } }
        }
        if ($s.type -eq 'range') {
          foreach ($k in 'min', 'max', 'step', 'default') { if ($null -eq $s.$k) { Err $rel "$ctx : range '$($s.id)' needs $k" } }
          if ($null -ne $s.min -and $null -ne $s.max -and $null -ne $s.step -and $s.step -gt 0) {
            if ((($s.max - $s.min) / $s.step) -gt 101) { Err $rel "$ctx : range '$($s.id)' has more than 101 steps" }
            if ($null -ne $s.default -and ($s.default -lt $s.min -or $s.default -gt $s.max)) { Err $rel "$ctx : range '$($s.id)' default outside min/max" }
            if ($null -ne $s.default -and ((($s.default - $s.min) % $s.step) -ne 0)) { Err $rel "$ctx : range '$($s.id)' default is not on a step" } }
        }
        if ($s.type -eq 'checkbox' -and $null -eq $s.default) { Warn $rel "$ctx : checkbox '$($s.id)' has no default (false)" }
      } }
    $script:ids = $ids
    & $chk $sc.settings 'settings'
    $btypes = @{}
    foreach ($b in @($sc.blocks)) { if (-not $b) { continue }
      if (-not $b.type) { Err $rel 'block without type'; continue }
      if ($btypes.ContainsKey($b.type)) { Err $rel "duplicate block type '$($b.type)'" }; $btypes[$b.type] = 1
      if (-not $b.name) { Err $rel "block '$($b.type)' has no name" }
      & $chk $b.settings "block:$($b.type)" }
    if ($sc.max_blocks -and $sc.max_blocks -gt 50) { Err $rel 'max_blocks above 50' }
    if ($sc.blocks -and @($sc.blocks).Count -gt 0) {
      $viaSnippets = $false
      $queue = New-Object System.Collections.Generic.Queue[string]; $seen = @{}
      foreach ($rm2 in [regex]::Matches($code, '\{%-?\s*render\s+[''"]([^''"]+)[''"]')) { $queue.Enqueue($rm2.Groups[1].Value) }
      while ($queue.Count -gt 0) { $sn = $queue.Dequeue(); if ($seen.ContainsKey($sn)) { continue }; $seen[$sn] = 1; $sp2 = Join-Path $T ('snippets\' + $sn + '.liquid'); if (-not (Test-Path $sp2)) { continue }
        $sc2 = [IO.File]::ReadAllText($sp2); if ($sc2 -match 'block\.shopify_attributes') { $viaSnippets = $true; break }
        foreach ($rm3 in [regex]::Matches($sc2, '\{%-?\s*render\s+[''"]([^''"]+)[''"]')) { $queue.Enqueue($rm3.Groups[1].Value) } }      if ($src -notmatch 'block\.shopify_attributes' -and -not $viaSnippets) { Err $rel 'section has blocks but never outputs {{ block.shopify_attributes }} (Theme Editor cannot select blocks)' }
      foreach ($m in [regex]::Matches($code, '\{%-?\s*when\s+[''"]([^''"]+)[''"]')) { if (-not $btypes.ContainsKey($m.Groups[1].Value)) { Err $rel "markup handles block type '$($m.Groups[1].Value)' that the schema does not define" } }
    }
    if (-not $sc.presets -and -not $sc.enabled_on -and -not $sc.templates -and -not $staticSections.ContainsKey($name)) { Warn $rel 'no presets: the section cannot be added from the Theme Editor' }
    if ($sc.presets) { foreach ($p in @($sc.presets)) { foreach ($pb in @($p.blocks)) { if ($pb -and -not $btypes.ContainsKey($pb.type)) { Err $rel "preset uses unknown block type '$($pb.type)'" } } } }
  }
}

# ---------- JSON templates and groups ----------
foreach ($k in @($parsed.Keys) | Where-Object { $_ -like 'templates/*.json' -or $_ -like 'sections/*.json' }) {
  $o = $parsed[$k]; if (-not $o.sections) { Err $k 'no "sections"'; continue }
  $orderIds = @($o.order)
  foreach ($p in $o.sections.PSObject.Properties) {
    $id = $p.Name; $inst = $p.Value
    if ($orderIds -notcontains $id) { Err $k "section '$id' is not in order[]" }
    if (-not $sectionFiles.ContainsKey($inst.type)) { Err $k "section '$id' uses unknown type '$($inst.type)'"; continue }
    $sc = $sectionSchemas[$inst.type]; if (-not $sc) { continue }
    $sids = @($sc.settings | Where-Object { $_.id } | ForEach-Object { $_.id })
    if ($inst.settings) { foreach ($sp in $inst.settings.PSObject.Properties) { if ($sids -notcontains $sp.Name) { Err $k "section '$id' sets unknown setting '$($sp.Name)'" } } }
    if ($inst.blocks) {
      $bo = @($inst.block_order)
      foreach ($bp in $inst.blocks.PSObject.Properties) {
        $bt = @($sc.blocks | Where-Object { $_.type -eq $bp.Value.type })
        if (-not $bt) { Err $k "section '$id' block '$($bp.Name)' has unknown type '$($bp.Value.type)'"; continue }
        if ($bo -notcontains $bp.Name) { Err $k "section '$id' block '$($bp.Name)' is not in block_order[]" }
        $bids = @($bt[0].settings | Where-Object { $_.id } | ForEach-Object { $_.id })
        if ($bp.Value.settings) { foreach ($bsp in $bp.Value.settings.PSObject.Properties) { if ($bids -notcontains $bsp.Name) { Err $k "section '$id' block '$($bp.Name)' sets unknown setting '$($bsp.Name)'" } } }
      }
      if ($sc.max_blocks -and @($inst.blocks.PSObject.Properties).Count -gt $sc.max_blocks) { Err $k "section '$id' has more blocks than max_blocks" }
    }
  }
}

if (-not $Quiet) {
  $errors | ForEach-Object { "ERROR   $_" }; $warns | ForEach-Object { "warning $_" }
  "lint: {0} error(s), {1} warning(s); {2} Liquid files, {3} JSON files" -f $errors.Count, $warns.Count, $liq.Count, $json.Count
}
[pscustomobject]@{ Errors = $errors.ToArray(); Warnings = $warns.ToArray() }
